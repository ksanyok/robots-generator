import { PRESETS, AI_CRAWLERS, SEO_CRAWLERS } from './presets.js';

export { PRESETS, AI_CRAWLERS, SEO_CRAWLERS } from './presets.js';

const normPath = (p) => (p === '' || /^([/*]|https?:)/i.test(p) ? p : `/${p}`);

/**
 * Build a robots.txt configuration from options.
 * @param {{preset?: keyof PRESETS, disallow?: string[], allow?: string[], sitemaps?: string[], blockAi?: boolean, blockSeo?: boolean,
 *   crawlDelay?: number, host?: string, extraGroups?: {agents: string[], disallow?: string[], allow?: string[]}[]}} options
 */
export function buildConfig(options = {}) {
  const preset = PRESETS[options.preset || 'default'];
  if (!preset) throw new TypeError(`Unknown preset "${options.preset}". Use one of: ${Object.keys(PRESETS).join(', ')}`);
  const groups = preset.groups.map((g) => ({ agents: [...g.agents], disallow: [...g.disallow], allow: [...g.allow] }));
  const star = groups.find((g) => g.agents.includes('*'));
  star.disallow.push(...(options.disallow || []).map(normPath));
  star.allow.push(...(options.allow || []).map(normPath));
  if (options.crawlDelay) star.crawlDelay = options.crawlDelay;
  if (options.blockAi) groups.push({ agents: [...AI_CRAWLERS], disallow: ['/'], allow: [], comment: 'AI training and AI search crawlers' });
  if (options.blockSeo) groups.push({ agents: [...SEO_CRAWLERS], disallow: ['/'], allow: [], comment: 'Third-party SEO crawlers' });
  for (const g of options.extraGroups || []) groups.push({ agents: g.agents, disallow: (g.disallow || []).map(normPath), allow: (g.allow || []).map(normPath) });
  return { groups, sitemaps: options.sitemaps || [], host: options.host };
}

/** Serialise a configuration to robots.txt text. */
export function renderRobots(config, options = {}) {
  const lines = [];
  if (options.header !== false) lines.push(`# robots.txt generated by robots-generator — https://github.com/ksanyok/robots-generator`, '');
  for (const g of config.groups) {
    if (g.comment) lines.push(`# ${g.comment}`);
    for (const a of g.agents) lines.push(`User-agent: ${a}`);
    const allow = [...new Set(g.allow)];
    const disallow = [...new Set(g.disallow)];
    if (!allow.length && !disallow.length) lines.push('Disallow:');
    for (const p of allow) lines.push(`Allow: ${p}`);
    for (const p of disallow) lines.push(`Disallow: ${p}`);
    if (g.crawlDelay) lines.push(`Crawl-delay: ${g.crawlDelay}`);
    lines.push('');
  }
  if (config.host) lines.push(`Host: ${config.host}`, '');
  for (const s of config.sitemaps) lines.push(`Sitemap: ${s}`);
  return `${lines.join('\n').replace(/\n+$/, '')}\n`;
}

/** Check a configuration for mistakes before it is published. */
export function lintConfig(config) {
  const out = [];
  const add = (level, code, message) => out.push({ level, code, message });
  const star = config.groups.find((g) => g.agents.includes('*'));
  if (star?.disallow.includes('/') && !star.allow.some((a) => a.length > 1)) add('warning', 'blocks-everything', 'User-agent: * is disallowed from the whole site. Use this only for staging sites.');
  for (const g of config.groups) {
    for (const p of [...g.disallow, ...g.allow]) {
      if (/\s/.test(p)) add('error', 'whitespace', `Path "${p}" contains whitespace.`);
      if (/^https?:/i.test(p)) add('error', 'absolute-path', `Path "${p}" must be relative to the site root, not a full URL.`);
    }
    for (const p of g.disallow) if (/^\/(.*\.)?(css|js)$|^\/(assets|static|_next\/static|wp-includes)\/?$/.test(p)) add('warning', 'blocks-resources', `Disallow: ${p} may block CSS/JS that search engines need to render pages.`);
  }
  for (const s of config.sitemaps) if (!/^https?:\/\//.test(s)) add('error', 'sitemap-relative', `Sitemap "${s}" must be an absolute URL.`);
  if (!config.sitemaps.length) add('info', 'no-sitemap', 'No sitemap URL added.');
  if (config.groups.some((g) => g.crawlDelay)) add('info', 'crawl-delay', 'Crawl-delay is ignored by Googlebot.');
  return out;
}

/** Build, lint and render in one call. */
export function generateRobots(options = {}) {
  const config = buildConfig(options);
  return { text: renderRobots(config, options), config, issues: lintConfig(config) };
}
